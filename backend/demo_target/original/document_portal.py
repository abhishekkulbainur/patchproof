"""
Document Portal -- controlled demo target for PatchProof.

SYNTHETIC DATA ONLY. This module is deliberately vulnerable. It is never
served on a network port: PatchProof's harness imports a working copy of it
inside a short-lived local subprocess and calls `handle()` directly.

Do not edit this file to "fix" it -- it is the pristine baseline that the
demo resets to. Patches are applied to the working copy under var/workspace/.
"""
from __future__ import annotations

import traceback
from dataclasses import dataclass, field

DEBUG = True

USERS = {
    "u-alice": {"id": "u-alice", "name": "Alice Example", "team": "finance"},
    "u-bob": {"id": "u-bob", "name": "Bob Example", "team": "support"},
}

# Server-side session store: session token -> user id.
SESSIONS = {
    "sess-alice-7f3a91": "u-alice",
    "sess-bob-2c8e40": "u-bob",
}

DOCUMENTS = {
    "doc-1041": {
        "id": "doc-1041",
        "owner_id": "u-alice",
        "title": "Q3 vendor contract (draft)",
        "body": "Synthetic contract text. Payment terms: net 45.",
    },
    "doc-1042": {
        "id": "doc-1042",
        "owner_id": "u-alice",
        "title": "Expense summary - September",
        "body": "Synthetic expense lines for the demo.",
    },
    "doc-2077": {
        "id": "doc-2077",
        "owner_id": "u-bob",
        "title": "Support rota - week 41",
        "body": "Synthetic on-call schedule.",
    },
}


@dataclass
class Request:
    method: str
    path: str
    session: str | None = None
    headers: dict = field(default_factory=dict)


@dataclass
class Response:
    status: int
    body: dict


def current_user(request):
    user_id = SESSIONS.get(request.session or "")
    return USERS.get(user_id) if user_id else None


def summarize(doc):
    return {"id": doc["id"], "title": doc["title"]}


def list_documents(request, user):
    docs = [summarize(d) for d in DOCUMENTS.values() if d["owner_id"] == user["id"]]
    return Response(200, {"documents": docs})


def get_document(request, user, doc_id):
    doc = DOCUMENTS.get(doc_id)
    if doc is None:
        return Response(404, {"error": "Document not found"})
    return Response(200, {"document": doc})


def handle(request):
    try:
        user = current_user(request)
        if user is None:
            return Response(401, {"error": "Authentication required"})
        parts = request.path.strip("/").split("/")
        if request.method == "GET" and parts == ["api", "documents"]:
            return list_documents(request, user)
        if request.method == "GET" and len(parts) == 3 and parts[:2] == ["api", "documents"]:
            return get_document(request, user, parts[2])
        return Response(404, {"error": "Route not found"})
    except Exception as exc:
        body = {"error": "Internal error"}
        if DEBUG:
            body["detail"] = str(exc)
            body["trace"] = traceback.format_exc()
        return Response(500, body)
